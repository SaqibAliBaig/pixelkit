const fs = require('fs');
let c = fs.readFileSync('src/pages/convert/index.astro', 'utf8');
c = c.replace(/href={`\/\$\{c\.from\}-to-\$\{c\.to\}`}/g, 'href={`/${c.from}-to-${c.to}/`}');
